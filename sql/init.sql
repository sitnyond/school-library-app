-- Complete database schema for a fresh Supabase project.
-- Contains tables, constraints, indexes, RLS policies, grants, and the
-- required singleton row in public.app_settings (no sample lookup/book data).

begin;

-- ---------------------------------------------------------------------
-- Helper function for role-based access control
-- Regular signed-in users default to 'teacher'; admins have
-- auth.users.raw_app_meta_data -> 'role' = 'admin'.
-- ---------------------------------------------------------------------

create or replace function public.current_user_role()
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', 'teacher');
$$;

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

create table if not exists public.book_types (
  id uuid primary key default gen_random_uuid(),
  name text not null unique
);

create table if not exists public.placements (
  id uuid primary key default gen_random_uuid(),
  name text not null unique
);

create table if not exists public.classes (
  id uuid primary key default gen_random_uuid(),
  name text not null unique
);

create table if not exists public.app_settings (
  id boolean primary key default true check (id),
  loan_days integer not null default 30 check (loan_days between 1 and 365),
  extension_days integer not null default 30 check (extension_days between 1 and 365)
);

-- Required singleton row so Settings updates have a target row.
insert into public.app_settings (id) values (true) on conflict (id) do nothing;

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text,
  publisher text,
  type_id uuid not null references public.book_types (id) on delete restrict,
  placement_id uuid not null references public.placements (id) on delete restrict,
  quantity integer not null default 1 check (quantity >= 1),
  created_at timestamptz not null default now()
);

create table if not exists public.loans (
  id uuid primary key default gen_random_uuid(),
  book_id bigint not null references public.books (id) on delete restrict,
  class_id uuid not null references public.classes (id) on delete restrict,
  borrower_name text,
  loaned_at date not null default current_date,
  due_date date not null,
  returned_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_by_email text default (auth.jwt() ->> 'email'),

  constraint loans_due_after_loan
    check (due_date >= loaned_at),
  constraint loans_anonymized_when_returned
    check (returned_at is null or borrower_name is null),
  constraint loans_name_when_active
    check (returned_at is not null or (borrower_name is not null and length(trim(borrower_name)) > 0))
);

-- ---------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------

create index if not exists books_type_id_idx on public.books (type_id);
create index if not exists books_placement_id_idx on public.books (placement_id);

create index if not exists loans_active_book_idx on public.loans (book_id) where returned_at is null;
create index if not exists loans_class_idx on public.loans (class_id);
create index if not exists loans_returned_at_idx on public.loans (returned_at);

-- ---------------------------------------------------------------------
-- Row Level Security (RLS)
-- ---------------------------------------------------------------------

alter table public.book_types enable row level security;
alter table public.placements enable row level security;
alter table public.classes enable row level security;
alter table public.app_settings enable row level security;
alter table public.books enable row level security;
alter table public.loans enable row level security;

-- books: any signed-in user can manage books
drop policy if exists "authenticated_all_books" on public.books;
create policy "authenticated_all_books"
  on public.books for all to authenticated
  using (true) with check (true);

-- loans: any signed-in user can manage loans
drop policy if exists "authenticated_all_loans" on public.loans;
create policy "authenticated_all_loans"
  on public.loans for all to authenticated
  using (true) with check (true);

-- book_types: authenticated can read, only admin can write
drop policy if exists "authenticated_read_book_types" on public.book_types;
drop policy if exists "admin_write_book_types" on public.book_types;

create policy "authenticated_read_book_types"
  on public.book_types for select to authenticated
  using (true);

create policy "admin_write_book_types"
  on public.book_types for all to authenticated
  using (public.current_user_role() = 'admin')
  with check (public.current_user_role() = 'admin');

-- placements: authenticated can read, only admin can write
drop policy if exists "authenticated_read_placements" on public.placements;
drop policy if exists "admin_write_placements" on public.placements;

create policy "authenticated_read_placements"
  on public.placements for select to authenticated
  using (true);

create policy "admin_write_placements"
  on public.placements for all to authenticated
  using (public.current_user_role() = 'admin')
  with check (public.current_user_role() = 'admin');

-- classes: authenticated can read, only admin can write
drop policy if exists "authenticated_read_classes" on public.classes;
drop policy if exists "admin_write_classes" on public.classes;

create policy "authenticated_read_classes"
  on public.classes for select to authenticated
  using (true);

create policy "admin_write_classes"
  on public.classes for all to authenticated
  using (public.current_user_role() = 'admin')
  with check (public.current_user_role() = 'admin');

-- app_settings: authenticated can read, only admin can update
drop policy if exists "authenticated_read_app_settings" on public.app_settings;
drop policy if exists "admin_update_app_settings" on public.app_settings;

create policy "authenticated_read_app_settings"
  on public.app_settings for select to authenticated
  using (true);

create policy "admin_update_app_settings"
  on public.app_settings for update to authenticated
  using (public.current_user_role() = 'admin')
  with check (public.current_user_role() = 'admin');

-- ---------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------

grant select, insert, update, delete on public.books to authenticated;
grant select, insert, update, delete on public.loans to authenticated;
grant select, insert, update, delete on public.book_types to authenticated;
grant select, insert, update, delete on public.placements to authenticated;
grant select, insert, update, delete on public.classes to authenticated;
grant select, update on public.app_settings to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.current_user_role() to authenticated;

commit;
